"""PreToolUse hook: stop Claude from editing files that Buck2 owns.

Claude Code sends the tool call as JSON on stdin. Exiting with status 2 blocks
the call and shows stderr to Claude as the reason.
"""

import json
import os
import sys

PROTECTED = ("buck-out", os.path.join(".claude", "hooks"))


def main() -> int:
    event = json.load(sys.stdin)
    tool_input = event.get("tool_input", {})
    path = tool_input.get("file_path") or tool_input.get("notebook_path")
    if not path:
        return 0

    # Claude Code passes absolute paths; `join` leaves those untouched.
    root = os.environ.get("CLAUDE_PROJECT_DIR", os.getcwd())
    rel = os.path.relpath(os.path.join(event.get("cwd", root), path), root)
    for protected in PROTECTED:
        if rel == protected or rel.startswith(protected + os.sep):
            print(
                f"{rel} is generated by Buck2; change the BUCK target that produces it instead.",
                file=sys.stderr,
            )
            return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
